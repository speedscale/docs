#!/usr/bin/env bash
#
# Regenerate the MCP tools/prompts reference page, the REST API reference
# page and the REST API's OpenAPI document from the proxymock binary, so they
# never drift from the actual server surface. Run this whenever the proxymock
# MCP tools or REST operations change.
# Kraken's post-release pipeline runs it against the exact proxymock
# release binary whose release notes it publishes.
#
#   ./scripts/gen-mcp-docs.sh          # use `proxymock` on PATH
#   PROXYMOCK=/path/to/proxymock ./scripts/gen-mcp-docs.sh
#
# The binary comes from the speedscale repo (`PROGRAM_NAME=proxymock make
# build` in speedctl, which stamps the version) or a normal proxymock
# install (~/.speedscale/proxymock). A plain `go build` reports version
# "undefined"; set PROXYMOCK_VERSION to the tag it was built from.
#
# The version that generated the page is recorded in VERSION_FILE. The
# release pipeline pins generation to the release version. This script
# refuses a binary older than the recorded one unless ALLOW_OLDER=1.
set -euo pipefail

cd "$(dirname "$0")/.."

OUT="docs/proxymock/how-it-works/mcp-tools.md"
VERSION_FILE="scripts/mcp-docs-version.txt"

# Resolve the proxymock binary: explicit override, then PATH, then the
# default install location.
BIN="${PROXYMOCK:-}"
if [ -z "${BIN}" ]; then
  if command -v proxymock >/dev/null 2>&1; then
    BIN="$(command -v proxymock)"
  elif [ -x "${HOME}/.speedscale/proxymock" ]; then
    BIN="${HOME}/.speedscale/proxymock"
  else
    echo "error: proxymock binary not found. Install it or set PROXYMOCK=/path/to/proxymock" >&2
    exit 1
  fi
fi

VERSION="${PROXYMOCK_VERSION:-}"
if [ -z "${VERSION}" ]; then
  VERSION="$("${BIN}" version --client 2>/dev/null | grep -Eo 'v[0-9]+\.[0-9]+\.[0-9]+[0-9A-Za-z.-]*' | head -n 1 || true)"
fi
if [ -z "${VERSION}" ]; then
  echo "error: cannot tell which proxymock version ${BIN} is. Set PROXYMOCK_VERSION=vX.Y.Z to the tag it was built from." >&2
  exit 1
fi

# Release part only: v2.5.1038-8-gabc123 (8 commits past v2.5.1038) -> v2.5.1038.
release_of() { printf '%s\n' "${1%%-*}"; }

if [ -f "${VERSION_FILE}" ] && [ "${ALLOW_OLDER:-}" != "1" ]; then
  recorded="$(release_of "$(tr -d '[:space:]' < "${VERSION_FILE}")")"
  current="$(release_of "${VERSION}")"
  lowest="$(printf '%s\n%s\n' "${recorded}" "${current}" | sort -V | head -n 1)"
  if [ "${current}" != "${recorded}" ] && [ "${lowest}" = "${current}" ]; then
    echo "error: ${OUT} was generated by proxymock ${recorded}, newer than ${VERSION}. Set ALLOW_OLDER=1 to roll it back anyway." >&2
    exit 1
  fi
fi

echo "Generating ${OUT} from ${BIN} (${VERSION})..." >&2
"${BIN}" mcp docs > "${OUT}"

# The REST API reference and its OpenAPI document come from the same binary.
# Older releases have no `mcp openapi`; leave the pages as they are then.
# Probe the subcommand list, not `mcp openapi --help`: cobra prints the parent
# help and exits 0 for --help even when the subcommand does not exist.
REST_OUT="docs/proxymock/how-it-works/rest-api-reference.md"
OPENAPI_OUT="static/proxymock/openapi-v1.json"
if "${BIN}" mcp --help 2>/dev/null | grep -qE '^[[:space:]]+openapi[[:space:]]'; then
  echo "Generating ${REST_OUT} and ${OPENAPI_OUT}..." >&2
  mkdir -p "$(dirname "${OPENAPI_OUT}")"
  "${BIN}" mcp openapi > "${OPENAPI_OUT}"
  "${BIN}" mcp openapi --markdown > "${REST_OUT}"
fi

printf '%s\n' "${VERSION}" > "${VERSION_FILE}"
echo "Done. Review the diff and commit ${OUT}, ${REST_OUT}, ${OPENAPI_OUT} and ${VERSION_FILE}." >&2
